"""
Generate one audio file for a whole book.

Sentences come from Lute's own language parser, so the audio lines up
with what the reader shows. Lute keeps a single audio file per book,
so the sentences are joined into one mp3 and the sentence start times
are written next to it as <audiofile>.sentences.json (Lute's own
bookmarks stay the user's).
"""

import json
import os
import re
import uuid
from datetime import datetime

import soundfile as sf

from ocarina.tts.service import synthesize_text_sentences
from ocarina.tts.stitch import stitch

TIMINGS_SUFFIX = ".sentences.json"


def page_sentences(language, text):
    "Sentences of one page of text, using the language's parser."
    sentences, current, has_word = [], [], False

    def flush():
        nonlocal current, has_word
        s = re.sub(r"\s+", " ", "".join(current).replace("¶", " ")).strip()
        if s and has_word:
            sentences.append(s)
        current, has_word = [], False

    for tok in language.parser.get_parsed_tokens(text, language):
        current.append(tok.token)
        has_word = has_word or tok.is_word
        if tok.is_end_of_sentence:
            flush()
    flush()
    return sentences


def book_sentences(book):
    "All sentences of a book as a list of {page, text}, in reading order."
    result = []
    for page in sorted(book.texts, key=lambda t: t.order):
        for s in page_sentences(book.language, page.text):
            result.append({"page": page.order, "text": s})
    return result


def timings_path(audio_path):
    "Where the sentence timings for an audio file live."
    return audio_path + TIMINGS_SUFFIX


def timings_info(audio_dir, audio_filename):
    "The timings file of an audio file as a dict, or None if it has none (or it cannot be read)."
    if not audio_filename:
        return None
    try:
        with open(timings_path(os.path.join(audio_dir, audio_filename)), encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def has_timings(audio_dir, audio_filename):
    "True if sentences can follow this audio (Ocarina made it, or you synced it with the text)."
    return bool(audio_filename) and os.path.exists(
        timings_path(os.path.join(audio_dir, audio_filename))
    )


def is_ocarina_audio(audio_dir, audio_filename):
    "True if the audio was generated by Ocarina: it has timings that came from generating it, not from syncing."
    info = timings_info(audio_dir, audio_filename)
    return info is not None and not info.get("aligned")


def generate_book_audio(  # pylint: disable=too-many-arguments,too-many-positional-arguments,too-many-locals
    book, supervisor, cache, model_id, audio_dir, voice, pause=0.5, on_progress=None, ref_text=None
):
    """
    Voice the whole book, write the mp3 and timings into audio_dir,
    and return the new audio filename (the caller saves it on the book).

    on_progress(done, total) is called after each sentence.
    """
    sentences = book_sentences(book)
    if not sentences:
        raise ValueError("Book has no text to voice.")
    lang = tts_lang(book.language)
    paths = synthesize_text_sentences(
        supervisor,
        cache,
        model_id,
        [s["text"] for s in sentences],
        lang,
        voice,
        lambda i, total: on_progress and on_progress(i + 1, total),
        ref_text,
    )
    audio, rate, starts = stitch(paths, pause)
    os.makedirs(audio_dir, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{stamp}_{uuid.uuid4().hex}.mp3"
    full = os.path.join(audio_dir, filename)
    sf.write(full, audio, rate, format="MP3")
    for s, start in zip(sentences, starts):
        s["start"] = start
    with open(timings_path(full), "w", encoding="utf-8") as f:
        json.dump(
            {"model": model_id, "language": lang, "sentences": sentences},
            f,
            ensure_ascii=False,
        )
    return filename


def tts_lang(language):
    """
    Two-letter TTS code of a Lute language: Dutch, Polish and French by name, and any other language that a speech model
    in the catalog lists. ValueError when no model can voice it.
    """
    from ocarina import translate  # pylint: disable=import-outside-toplevel
    from ocarina.tts import models  # pylint: disable=import-outside-toplevel

    names = {
        "dutch": "nl",
        "polish": "pl",
        "polski": "pl",
        "french": "fr",
        "français": "fr",
        "nederlands": "nl",
    }
    code = names.get(language.name.strip().lower()) or translate.code_for(language.name)
    if code is None or not any(models.covers(m, code) for m in models.speech_models()):
        raise ValueError(f"No TTS language code for '{language.name}'.")
    return code
